/**
 * Phase 16 — AI-Assisted Automation
 *
 * Root panel that hosts all 4 AI sub-features:
 *   16.A — Natural Language Workflow Builder
 *   16.B — AI Detection Advisor
 *   16.C — Smart Selector Healing
 *   16.D — Behaviour Pattern Library
 *
 * Includes the API key setup panel so users can configure their
 * Anthropic key without leaving this section.
 */

import React, { useEffect, useState } from 'react'
import {
  Bot,
  Wand2,
  Brain,
  Wrench,
  Activity,
  Key,
  CheckCircle,
  AlertCircle,
  Eye,
  EyeOff,
  Loader2,
  Info,
  ToggleLeft,
  ToggleRight
} from 'lucide-react'
import { Header } from '../Layout/Header'
import { WorkflowGenerator } from './WorkflowGenerator'
import { DetectionAdvisor } from './DetectionAdvisor'
import { SelectorHealer } from './SelectorHealer'
import { BehaviorLibrary } from './BehaviorLibrary'
import { useProfileStore } from '../../stores/profileStore'
import type { AiUsageStatus, AutomationStep, DetectionTestResult, NavSection } from '../../types'

type Tab = '16a' | '16b' | '16c' | '16d'

const TABS: { id: Tab; icon: React.ElementType; label: string; badge?: string }[] = [
  { id: '16a', icon: Wand2,     label: 'Workflow Builder', badge: 'NEW' },
  { id: '16b', icon: Brain,     label: 'Detection Advisor' },
  { id: '16c', icon: Wrench,    label: 'Selector Healing' },
  { id: '16d', icon: Activity,  label: 'Behaviour Library' }
]

interface Props {
  onNavigate?: (section: NavSection) => void
}

export function AIAssistant({ onNavigate }: Props) {
  const [tab, setTab]                   = useState<Tab>('16a')
  const [status, setStatus]             = useState<AiUsageStatus | null>(null)
  const [apiKeyInput, setApiKeyInput]   = useState('')
  const [showKey, setShowKey]           = useState(false)
  const [savingKey, setSavingKey]       = useState(false)
  const [keyError, setKeyError]         = useState<string | null>(null)
  const [keySaved, setKeySaved]         = useState(false)
  const [showSetup, setShowSetup]       = useState(false)
  const [latestResult, setLatestResult] = useState<DetectionTestResult | null>(null)
  const [selectedProfileId, setSelectedProfileId] = useState<string>('')

  const { profiles } = useProfileStore()

  useEffect(() => {
    loadStatus()
    loadLatestDetectionResult()
  }, [])

  const loadStatus = async () => {
    try {
      const s = await (window.api as any).ai.status()
      setStatus(s)
      if (!s.configured) setShowSetup(true)
    } catch {
      // non-fatal
    }
  }

  const loadLatestDetectionResult = async () => {
    try {
      const results = await (window.api as any).detection.results()
      if (results?.length > 0) {
        setLatestResult(results[results.length - 1])
      }
    } catch {
      // non-fatal
    }
  }

  const handleSaveKey = async () => {
    if (!apiKeyInput.trim()) return
    setSavingKey(true)
    setKeyError(null)
    try {
      const updated = await (window.api as any).ai.setApiKey(apiKeyInput.trim())
      setStatus(updated)
      setKeySaved(true)
      setApiKeyInput('')
      setShowSetup(false)
      setTimeout(() => setKeySaved(false), 3000)
    } catch (e: any) {
      setKeyError(e.message ?? 'Failed to save API key')
    } finally {
      setSavingKey(false)
    }
  }

  const handleToggleEnabled = async () => {
    if (!status) return
    try {
      const updated = await (window.api as any).ai.setEnabled(!status.enabled)
      setStatus(updated)
    } catch {
      // non-fatal
    }
  }

  const handleWorkflowImport = async (steps: AutomationStep[], name: string) => {
    try {
      await (window.api as any).workflows.create({ name, steps, description: 'Generated by AI Assistant' })
      // Navigate to automation builder
      onNavigate?.('automation')
    } catch (e: any) {
      console.error('Failed to create workflow:', e.message)
    }
  }

  const usagePercent = status ? Math.round((status.callsUsed / status.callsMax) * 100) : 0
  const usageColor   = usagePercent >= 90 ? 'bg-red-500' : usagePercent >= 70 ? 'bg-amber-500' : 'bg-ghost-500'

  return (
    <div className="flex flex-col h-full overflow-hidden">
      <Header title="AI Assistant" subtitle="Phase 16 — AI-Assisted Automation" />

      <div className="flex-1 overflow-y-auto">
        <div className="max-w-3xl mx-auto px-6 py-5 space-y-5">

          {/* Status bar */}
          {status && (
            <div className="flex items-center gap-3 p-3 bg-slate-800/60 border border-slate-700 rounded-lg text-sm">
              <Bot className="w-4 h-4 text-ghost-400 shrink-0" />

              {/* Configured/status indicator */}
              {status.configured ? (
                <div className="flex items-center gap-1.5 text-green-400">
                  <CheckCircle className="w-3.5 h-3.5" />
                  API key configured
                </div>
              ) : (
                <div className="flex items-center gap-1.5 text-amber-400">
                  <AlertCircle className="w-3.5 h-3.5" />
                  API key not set
                </div>
              )}

              <div className="h-4 w-px bg-slate-700" />

              {/* Enabled toggle */}
              <button onClick={handleToggleEnabled} className="flex items-center gap-1.5 text-slate-400 hover:text-slate-200">
                {status.enabled
                  ? <ToggleRight className="w-4 h-4 text-ghost-400" />
                  : <ToggleLeft className="w-4 h-4" />
                }
                {status.enabled ? 'Enabled' : 'Disabled'}
              </button>

              <div className="flex-1" />

              {/* Call budget */}
              <div className="flex items-center gap-2 text-xs text-slate-400">
                <div className="w-24 h-1.5 bg-slate-700 rounded-full overflow-hidden">
                  <div className={`h-full rounded-full transition-all ${usageColor}`} style={{ width: `${usagePercent}%` }} />
                </div>
                {status.callsUsed}/{status.callsMax} calls
              </div>

              {/* Configure button */}
              <button
                onClick={() => setShowSetup((v) => !v)}
                className="flex items-center gap-1.5 text-xs text-ghost-400 hover:text-ghost-300 px-2 py-1 rounded bg-ghost-500/10"
              >
                <Key className="w-3.5 h-3.5" />
                {status.configured ? 'Change Key' : 'Set API Key'}
              </button>
            </div>
          )}

          {/* API key setup panel */}
          {showSetup && (
            <div className="p-4 bg-slate-800/60 border border-slate-700 rounded-lg space-y-3">
              <div className="flex items-start gap-2 text-xs text-slate-400">
                <Info className="w-4 h-4 shrink-0 mt-0.5 text-ghost-400" />
                Enter your Anthropic API key to enable AI features. The key is stored locally and never sent to any server other than api.anthropic.com.
              </div>
              <div className="flex gap-2">
                <div className="relative flex-1">
                  <input
                    type={showKey ? 'text' : 'password'}
                    value={apiKeyInput}
                    onChange={(e) => setApiKeyInput(e.target.value)}
                    placeholder="sk-ant-api03-..."
                    className="w-full bg-slate-900 border border-slate-600 rounded-lg px-3 py-2 text-sm text-white font-mono placeholder-slate-600 focus:outline-none focus:border-ghost-500 pr-9"
                    onKeyDown={(e) => e.key === 'Enter' && handleSaveKey()}
                  />
                  <button
                    onClick={() => setShowKey((v) => !v)}
                    className="absolute right-2.5 top-1/2 -translate-y-1/2 text-slate-500 hover:text-slate-300"
                  >
                    {showKey ? <EyeOff className="w-4 h-4" /> : <Eye className="w-4 h-4" />}
                  </button>
                </div>
                <button
                  onClick={handleSaveKey}
                  disabled={!apiKeyInput.trim() || savingKey}
                  className="px-4 py-2 bg-ghost-600 hover:bg-ghost-700 disabled:bg-slate-700 disabled:text-slate-500 text-white text-sm font-medium rounded-lg transition-colors shrink-0"
                >
                  {savingKey ? <Loader2 className="w-4 h-4 animate-spin" /> : 'Save'}
                </button>
              </div>
              {keyError && <p className="text-xs text-red-400">{keyError}</p>}
              {keySaved && (
                <div className="flex items-center gap-1.5 text-xs text-green-400">
                  <CheckCircle className="w-3.5 h-3.5" />
                  API key saved successfully
                </div>
              )}
            </div>
          )}

          {/* Feature tabs */}
          <div className="flex gap-1 bg-slate-800/40 rounded-lg p-1">
            {TABS.map(({ id, icon: Icon, label, badge }) => (
              <button
                key={id}
                onClick={() => setTab(id)}
                className={`flex-1 flex items-center justify-center gap-2 px-2 py-2 rounded-md text-xs font-medium transition-colors ${
                  tab === id
                    ? 'bg-ghost-600/20 text-ghost-300'
                    : 'text-slate-400 hover:text-slate-200'
                }`}
              >
                <Icon className="w-3.5 h-3.5 shrink-0" />
                <span className="hidden sm:inline">{label}</span>
                {badge && (
                  <span className="text-[9px] px-1 py-0.5 rounded bg-ghost-500/30 text-ghost-400 leading-none">
                    {badge}
                  </span>
                )}
              </button>
            ))}
          </div>

          {/* Profile picker (used by 16.D) */}
          {tab === '16d' && (
            <div className="flex items-center gap-2">
              <label className="text-xs text-slate-400 shrink-0">Apply to profile:</label>
              <select
                value={selectedProfileId}
                onChange={(e) => setSelectedProfileId(e.target.value)}
                className="flex-1 bg-slate-800 border border-slate-700 rounded-lg px-3 py-2 text-sm text-white focus:outline-none focus:border-ghost-500"
              >
                <option value="">— select profile —</option>
                {profiles.map((p) => (
                  <option key={p.id} value={p.id}>{p.name}</option>
                ))}
              </select>
            </div>
          )}

          {/* Tab content */}
          <div className="bg-slate-800/40 border border-slate-700 rounded-xl p-5">
            {tab === '16a' && (
              <>
                <h3 className="text-sm font-semibold text-white mb-1 flex items-center gap-2">
                  <Wand2 className="w-4 h-4 text-ghost-400" />
                  Natural Language Workflow Builder
                </h3>
                <p className="text-xs text-slate-400 mb-4">
                  Describe a task in plain English and get a ready-to-run automation workflow.
                </p>
                <WorkflowGenerator onImport={handleWorkflowImport} />
              </>
            )}

            {tab === '16b' && (
              <>
                <h3 className="text-sm font-semibold text-white mb-1 flex items-center gap-2">
                  <Brain className="w-4 h-4 text-ghost-400" />
                  AI Detection Advisor
                </h3>
                <p className="text-xs text-slate-400 mb-4">
                  Analyse your latest detection test results and get prioritised fix recommendations.
                </p>
                <DetectionAdvisor
                  latestResult={latestResult}
                  onNavigateToDetection={() => onNavigate?.('detection')}
                />
              </>
            )}

            {tab === '16c' && (
              <>
                <h3 className="text-sm font-semibold text-white mb-1 flex items-center gap-2">
                  <Wrench className="w-4 h-4 text-ghost-400" />
                  Smart Selector Healing
                </h3>
                <p className="text-xs text-slate-400 mb-4">
                  Paste a broken CSS selector and the page HTML to get an AI-suggested replacement.
                </p>
                <SelectorHealer />
              </>
            )}

            {tab === '16d' && (
              <>
                <h3 className="text-sm font-semibold text-white mb-1 flex items-center gap-2">
                  <Activity className="w-4 h-4 text-ghost-400" />
                  Behaviour Pattern Library
                </h3>
                <p className="text-xs text-slate-400 mb-4">
                  Apply one of 10 realistic human-behaviour profiles to a browser session.
                </p>
                <BehaviorLibrary selectedProfileId={selectedProfileId} />
              </>
            )}
          </div>

          {/* Phase badge */}
          <div className="text-center">
            <span className="text-[10px] text-slate-600">
              Phase 16 — AI-Assisted Automation · powered by Anthropic Claude
            </span>
          </div>
        </div>
      </div>
    </div>
  )
}
